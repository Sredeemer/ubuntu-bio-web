/**
 * Filter African taxa locally by search string (taxon_id or name prefix/substring).
 */
export function searchAfricanTaxa(query: string, limit: number = 10): AfricanTaxon[] {
  const q = query.trim().toLowerCase();
  if (!q) {
    return AFRICAN_TAXA.filter((t) => t.is_priority && !t.is_prohibited).slice(0, limit);
  }

  const isNumeric = /^\d+$/.test(q);
  const qInt = isNumeric ? parseInt(q, 10) : null;

  const scored: Array<{ score: number; taxon: AfricanTaxon }> = [];

  for (const taxon of AFRICAN_TAXA) {
    let score = 0;
    const sName = taxon.scientific_name.toLowerCase();
    const cName = taxon.common_name.toLowerCase();
    const genus = taxon.genus.toLowerCase();
    const family = taxon.family.toLowerCase();

    if (isNumeric && qInt !== null) {
      if (taxon.taxon_id === qInt) score = 200;
      else if (taxon.taxon_id.toString().startsWith(q)) score = 120;
      else if (taxon.taxon_id.toString().includes(q)) score = 80;
    } else if (sName === q || cName === q) {
      score = 150;
    } else if (sName.startsWith(q)) {
      score = 100;
    } else if (cName.startsWith(q)) {
      score = 90;
    } else if (genus.startsWith(q)) {
      score = 80;
    } else if (sName.split(/\s+/).some((w) => w.startsWith(q))) {
      score = 75;
    } else if (cName.split(/\s+/).some((w) => w.startsWith(q))) {
      score = 70;
    } else if (sName.includes(q)) {
      score = 50;
    } else if (cName.includes(q)) {
      score = 45;
    } else if (genus.includes(q) || family.includes(q)) {
      score = 40;
    }

    if (score > 0) {
      scored.push({ score, taxon });
    }
  }

  scored.sort((a, b) => b.score - a.score || a.taxon.scientific_name.localeCompare(b.taxon.scientific_name));
  return scored.slice(0, limit).map((s) => s.taxon);
}
